#!/usr/bin/env python3
"""Derived offline inventory; learning-set JSONs remain the content source of truth."""
import argparse
import hashlib
import json
import re
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'data/offline-assets.bundle.js'
TYPES = {'.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png',
         '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.mp3': 'audio/mpeg', '.wav': 'audio/wav'}


def referenced(value):
    if isinstance(value, dict):
        for child in value.values():
            yield from referenced(child)
    elif isinstance(value, list):
        for child in value:
            yield from referenced(child)
    elif isinstance(value, str) and value.startswith('assets/'):
        yield value.split('?')[0]


def build():
    paths = set()
    for source in [*sorted((ROOT / 'data/sets').glob('*.json')),
                   ROOT / 'data/minigames/colours_hidden_object.json',
                   ROOT / 'assets/audio/feedback_en_01/feedback_en_01.json',
                   ROOT / 'assets/audio/audio-manifest.json']:
        paths.add(source.relative_to(ROOT).as_posix())
        paths.update(referenced(json.loads(source.read_text(encoding='utf-8'))))
    for path in list(paths):
        if path.startswith('assets/audio/') and path.endswith(('.mp3', '.wav')):
            cue = str(PurePosixPath(path.replace('assets/audio/', 'assets/lipsync/')).with_suffix('.json'))
            if (ROOT / cue).exists():
                paths.add(cue)
    # Existing UI paths are declared by app.js / the shell precache; don't maintain
    # a second list of avatar frames, covers or victory sounds here.
    for source in ['app.js', 'service-worker.js']:
        paths.update(p.split('?')[0] for p in re.findall(r'"(?:\./)?(assets/[^"\s]+)"', (ROOT / source).read_text())
                     if (ROOT / p.split('?')[0]).is_file())
    files = {}
    # Script bundles belong to the shell, not to the media/JSON hash store.
    for path in sorted(p for p in paths if PurePosixPath(p).suffix in TYPES):
        content = (ROOT / path).read_bytes()
        files[path] = {'sha256': hashlib.sha256(content).hexdigest(), 'bytes': len(content),
                       'type': TYPES.get(Path(path).suffix, 'application/octet-stream')}
    payload = json.dumps({'schemaVersion': 1, 'files': files}, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    digest = hashlib.sha256(payload.encode()).hexdigest()[:16]
    return '// Generated by tools/build_offline_assets.py. Do not edit.\nglobalThis.LERNWORT_OFFLINE_ASSETS = ' + payload + ';\n', digest, len(files)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, revision, count = build()
    changed = not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content
    updated = {}
    for name in ['index.html', 'service-worker.js']:
        source = (ROOT / name).read_text(encoding='utf-8')
        next_source = re.sub(r'offline-assets\.bundle\.js\?v=[\w-]+', 'offline-assets.bundle.js?v=' + revision, source)
        if source != next_source:
            changed = True
        updated[name] = next_source
    if args.check:
        if changed:
            raise SystemExit('Offline inventory is stale: run python3 tools/build_offline_assets.py')
    else:
        OUTPUT.write_text(content, encoding='utf-8')
        for name, source in updated.items():
            (ROOT / name).write_text(source, encoding='utf-8')
    print(f'Offline inventory: {count} files, revision {revision}, current={not changed or not args.check}')


if __name__ == '__main__':
    main()
